/* محاسبه حروف اول برای آواتارهای بدون عکس */
export function getInitials(name) {
  if (!name) return "ر";
  const parts = name.trim().split(/\s+/);
  if (parts.length >= 2) {
    return `${parts[0][0]} ${parts[1][0]}`;
  }
  return parts[0][0];
}

